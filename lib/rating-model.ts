/**
 * Estimated match rating for a player who ran the CPU. EA's rating on that line is the average of
 * the player's own and every CPU teammate's, and EA doesn't send the CPU's, so the player's own can't
 * be worked out. This estimates it from what EA's rating is made of, using only the player's own
 * numbers (the hidden counters) plus the result.
 *
 * A linear model trained by scripts/rating-model.mjs on the human-only lines of the EA FC Pro Clubs
 * API research dataset (github.com/Interactive-63/eafc-pro-clubs-api-research), then tuned on our own
 * games without the CPU. No imports, so the script can load this file with --experimental-strip-types.
 */

type Get = (key: string) => number;

/** Counter ids the model reads (every counter in the research dataset). */
const POSITIONS = ["goalkeeper", "defender", "midfielder", "forward"];
const BY_POSITION = [214, 11, 217, 215, 164, 6, 174];

/**
 * The model's inputs, by name. `h` reads EA's headline fields of the player line, `c` a counter.
 * On a +CPU line EA's saves and red cards may be the CPU's, so they're left out unless own.
 */
export function ratingFeatures(h: Get, c: Get, pos: string, counterIds: number[], cpu: boolean): Record<string, number> {
  const f: Record<string, number> = { "1": 1 };
  for (const id of counterIds) f[`c${id}`] = c(String(id));
  for (const p of POSITIONS) f[`pos:${p}`] = pos === p ? 1 : 0;
  f.win = h("wins");
  f.loss = h("losses");
  f.conceded = h("goalsconceded");
  f.cs_any = h("cleansheetsany");
  f.cs_def = h("cleansheetsdef");
  f.cs_gk = h("cleansheetsgk");
  f.saves = cpu && pos !== "goalkeeper" ? 0 : h("saves");
  f.red = cpu ? 0 : h("redcards");
  for (const id of BY_POSITION) for (const p of POSITIONS) f[`c${id}@${p}`] = pos === p ? c(String(id)) : 0;
  for (const p of POSITIONS) f[`conceded@${p}`] = pos === p ? h("goalsconceded") : 0;
  return f;
}

/** The estimate for one EA player line (strings, as EA sends them), rounded to 0.1. */
export function estimateRating(line: Record<string, unknown>, cpu: boolean): number | null {
  if (!RATING_MODEL.weights) return null;
  const counters = new Map<string, number>();
  for (const i of [0, 1, 2, 3]) {
    for (const part of String(line[`match_event_aggregate_${i}`] ?? "").split(",")) {
      const [id, count] = part.split(":");
      if (id && Number.isFinite(Number(count))) counters.set(id, (counters.get(id) ?? 0) + Number(count));
    }
  }
  if (!counters.size) return null;
  const num = (v: unknown) => (v === undefined || v === null || v === "" ? 0 : Number(v));
  const f = ratingFeatures((k) => num(line[k]), (id) => counters.get(id) ?? 0, String(line.pos ?? ""), RATING_MODEL.counterIds, cpu);
  let raw = 0;
  for (const [k, w] of Object.entries(RATING_MODEL.weights)) raw += w * (f[k] ?? 0);
  const tuned = RATING_MODEL.tune.a + RATING_MODEL.tune.b * raw;
  return Math.round(Math.min(10, Math.max(3, tuned)) * 10) / 10;
}

